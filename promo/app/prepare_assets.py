"""Build the promo mock's real-image assets from promo/pages and promo/cleaned.

Writes into <mc-ui>/public/promo/ and <mc-ui>/src/lib/api/promo-data.js.
Every pixel comes from the real pipeline outputs; nothing is synthesised.
"""
import json, sys, os
import numpy as np
from PIL import Image, ImageFilter

PROMO = '/Users/caved/dev/manga-cleaner/promo'
UI = sys.argv[1]
OUT = os.path.join(UI, 'public/promo')
for d in ('src', 'layer', 'det'):
    os.makedirs(os.path.join(OUT, d), exist_ok=True)

PAGES = ['010', '025', '047', '048', '049', '050', '100']
data = json.load(open(f'{PROMO}/cleaned/regions.json'))
real = {p['page'].split('-')[1]: p for p in data['pages']}

PROXY_SHORT = 1024
def proxy_size(w, h):
    short, long = min(w, h), max(w, h)
    ps = min(short, PROXY_SHORT)
    pl = long if ps == short else max(ps, round(long * ps / short))
    return (ps, pl) if h >= w else (pl, ps)

manifest = {'pages': {}}
js_pages = {}
for n in PAGES:
    src = Image.open(f'{PROMO}/pages/page-{n}.png').convert('RGB')
    W, H = src.size
    pw, ph = proxy_size(W, H)
    sx, sy = pw / W, ph / H
    src.resize((pw, ph), Image.LANCZOS).save(f'{OUT}/src/page-{n}.png', optimize=False)
    entry = {'w': W, 'h': H, 'pw': pw, 'ph': ph, 'layers': {}, 'dets': {}}
    regions = []
    p = real.get(n)
    if p:
        clean = np.array(Image.open(f'{PROMO}/cleaned/page-{n}-clean.png').convert('RGB'))
        mask = np.array(Image.open(f'{PROMO}/cleaned/page-{n}-mask.png').convert('L'))
        srcA = np.array(src)
        diff = (np.abs(clean.astype(int) - srcA.astype(int)).max(-1) > 0)
        # Widen by 4 px: the cleaned page equals the source there, so this
        # changes no picture, and it keeps downscaled stroke edges from
        # leaving a ghost of the lettering around a patch.
        diff = np.array(Image.fromarray((diff * 255).astype(np.uint8)).filter(ImageFilter.MaxFilter(9))) > 0
        for k, r in enumerate(p['regions']):
            x, y, w, h = r['bbox']
            pb = r.get('patchBbox') or r['bbox']
            regions.append({
                'k': k, 'bbox': [x / W * 100, y / H * 100, w / W * 100, h / H * 100],
                'kind': 'bubble' if r['kind'] == 'in-bubble' else 'sfx',
                'status': r['status'], 'engine': r.get('engine'),
                'reason': r.get('reason'), 'stage': r.get('stage'),
            })
            # Detection mask: the real mask inside the patch box, page pixels, tight bounds.
            px, py, pw_, ph_ = pb
            m = mask[py:py + ph_, px:px + pw_]
            ys, xs = np.nonzero(m)
            if len(xs):
                x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
                crop = m[y0:y1, x0:x1]
                rgba = np.zeros((*crop.shape, 4), np.uint8)
                rgba[..., :3] = 255
                rgba[..., 3] = crop
                Image.fromarray(rgba, 'RGBA').save(f'{OUT}/det/page-{n}-r{k}.png')
                entry['dets'][k] = [int(px + x0), int(py + y0), int(x1 - x0), int(y1 - y0)]
            if r['status'] != 'cleaned':
                continue
            # Layer: the real cleaned pixels inside the patch box, see-through
            # wherever the cleaned page equals the source. Proxy pixels.
            d = diff[py:py + ph_, px:px + pw_]
            ys, xs = np.nonzero(d)
            if not len(xs):
                continue
            x0, x1, y0, y1 = px + xs.min(), px + xs.max() + 1, py + ys.min(), py + ys.max() + 1
            # proxy-space box, padded 1px so resampling keeps the edges
            bx0 = max(0, int(np.floor(x0 * sx)) - 1); by0 = max(0, int(np.floor(y0 * sy)) - 1)
            bx1 = min(pw, int(np.ceil(x1 * sx)) + 1); by1 = min(ph, int(np.ceil(y1 * sy)) + 1)
            fx0, fy0 = int(np.floor(bx0 / sx)), int(np.floor(by0 / sy))
            fx1, fy1 = min(W, int(np.ceil(bx1 / sx))), min(H, int(np.ceil(by1 / sy)))
            alpha = np.zeros((H, W), np.uint8)
            alpha[y0:y1, x0:x1] = (diff[y0:y1, x0:x1] * 255).astype(np.uint8)
            tile = np.dstack([clean[fy0:fy1, fx0:fx1], alpha[fy0:fy1, fx0:fx1]])
            img = Image.fromarray(tile, 'RGBA').resize((bx1 - bx0, by1 - by0), Image.LANCZOS)
            img.save(f'{OUT}/layer/page-{n}-r{k}.png')
            entry['layers'][k] = [bx0, by0, bx1 - bx0, by1 - by0]
    manifest['pages'][n] = entry
    js_pages[n] = {'width': W, 'height': H, 'regions': regions}

manifest['chapters'] = {
    'bj-regards-ch2': PAGES,
    'bj-strip-ch1': ['010', '025', '100'],
}
json.dump(manifest, open(f'{OUT}/manifest.json', 'w'))
with open(os.path.join(UI, 'src/lib/api/promo-data.js'), 'w') as f:
    f.write('// Generated by promo/app/prepare_assets.py from promo/cleaned/regions.json. Do not edit.\n')
    f.write('export const PROMO_PAGES = ' + json.dumps(js_pages) + '\n')
print({n: (len(e['layers']), len(e['dets'])) for n, e in manifest['pages'].items()})
